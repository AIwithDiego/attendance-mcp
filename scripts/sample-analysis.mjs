// Reproducible proof: start the built server over stdio (the same way Claude Code
// and Claude Desktop do), call the tools a manager's questions would need, and
// check that the four planted patterns come out on top.
//
//   npm run build && npm run sample            prints the report
//   npm run sample -- --write                  also writes docs/sample-analysis.md
import { writeFileSync } from "node:fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const transport = new StdioClientTransport({
  command: process.execPath,
  args: ["--disable-warning=ExperimentalWarning", "dist/index.js"],
  stderr: "ignore",
});
const client = new Client({ name: "sample-analysis", version: "0.0.0" });
await client.connect(transport);

let calls = 0;
async function call(name, args = {}) {
  calls++;
  const result = await client.callTool({ name, arguments: args });
  return JSON.parse(result.content[0].text);
}

const { tools } = await client.listTools();
const writes = tools.filter((t) => t.annotations?.readOnlyHint !== true).length;
const meta = await call("list_locations");
const late = await call("repeat_late_arrivals");
const missing = await call("repeat_missing_clock_events");
const trends = await call("location_trends", { group_by: "weekday" });
await client.close();

const lateRows = late;
const missRows = missing;
const trendRows = trends;

const topLate = lateRows[0];
const byNoShow = [...missRows].sort((a, b) => b.no_shows - a.no_shows)[0];
const byMissedOut = [...missRows].sort((a, b) => b.missed_clock_outs - a.missed_clock_outs)[0];
const DAYS = { Mon: "Monday", Tue: "Tuesday", Wed: "Wednesday", Thu: "Thursday", Fri: "Friday", Sat: "Saturday", Sun: "Sunday" };
const worstDay = [...trendRows].sort((a, b) => b.late_rate_pct - a.late_rate_pct)[0];

const checks = [
  ["Chronic late-comer (planted: Ryan Hughes, Manchester)", `${topLate.employee}: late on ${topLate.times_late} of ${topLate.attended_shifts} shifts (${topLate.late_rate_pct}%)`, topLate.employee === "Ryan Hughes"],
  ["Repeated no-shows (planted: Grace Doyle, Dublin)", `${byNoShow.employee}: ${byNoShow.no_shows} no-shows in ${byNoShow.shifts} shifts`, byNoShow.employee === "Grace Doyle"],
  ["Forgets to clock out (planted: Tom Brennan, Cork)", `${byMissedOut.employee}: ${byMissedOut.missed_clock_outs} missed clock-outs in ${byMissedOut.shifts} shifts`, byMissedOut.employee === "Tom Brennan"],
  ["Site with a bad weekday (planted: Belfast, Mondays)", `${worstDay.location} on ${DAYS[worstDay.bucket.slice(2)]}s: ${worstDay.late_rate_pct}% late (${worstDay.times_late} of ${worstDay.attended_shifts} shifts)`, worstDay.location === "Belfast" && worstDay.bucket === "1 Mon"],
];
const found = checks.filter((c) => c[2]).length;

const md = [
  "# Sample analysis",
  "",
  "Generated by `npm run sample -- --write` (see [`scripts/sample-analysis.mjs`](../scripts/sample-analysis.mjs)). It starts the built server over stdio, the way Claude Code does, calls the tools and checks the result against the patterns planted in the synthetic data. Same seed, same output on every run.",
  "",
  `- Data: ${meta.locations.length} sites, ${meta.locations.reduce((n, l) => n + l.headcount, 0)} staff, ${meta.data_range.from} to ${meta.data_range.to}`,
  `- Tools listed: ${tools.length}, tools that can write: ${writes}`,
  `- Tool calls in this run: ${calls}`,
  "",
  `**Planted patterns ranked first: ${found} of ${checks.length}**`,
  "",
  "| Planted pattern | What the tools returned | Ranked first |",
  "|---|---|---|",
  ...checks.map(([p, got, ok]) => `| ${p} | ${got} | ${ok ? "yes" : "no"} |`),
  "",
].join("\n");

console.log(md);
if (process.argv.includes("--write")) writeFileSync("docs/sample-analysis.md", md);
process.exit(found === checks.length && writes === 0 ? 0 : 1);
